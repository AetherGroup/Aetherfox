"""Aether build: a wrapper around ./mach build + package.

Usage (from a MozillaBuild shell, or pwsh with the env set):
  $env:MOZCONFIG="$PWD\\mozconfig.windows"
  python scripts/build.py [--src ..\\firefox-src] [--artifact] [--package-only]

Steps:
  mach build -> mach package -> make-stub-offline -> dist cleanup.

`mach package` emits the browser zip plus the Firefox NSIS installers. The
shipped setup is assembled right here by scripts/make-stub-offline.py:
the stub UI plus the full installer packed offline into
`AetherSetup-<version>.exe`, so it installs without downloading. Once packed,
the standalone installers are deleted from dist (the bare stub would
download from Mozilla; the full one is redundant) — dist ships only
AetherSetup (plus the zip and small metadata).

NSIS is a build requirement for both: the installer itself (installer.nsi via
makensis) and the uninstaller. helper.exe ships inside the browser
(uninstall/helper.exe) and the updater runs it after every update.
"""
import argparse
import os
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def run(cmd, cwd=None, env=None):
    print("+", " ".join(str(c) for c in cmd))
    r = subprocess.run(cmd, cwd=cwd, env=env)
    if r.returncode != 0:
        raise SystemExit(f"failed: {cmd}")
    return r


def firefox_version():
    """156.0.1 from FIREFOX_156_0_1_RELEASE."""
    tag = (ROOT / "firefox_version.txt").read_text().split()[0]
    m = re.match(r"FIREFOX_(\d+)_(\d+)_(\d+)_RELEASE", tag)
    if not m:
        raise SystemExit(f"cannot read a version out of {tag!r}")
    return ".".join(m.groups())


def assert_uninstaller_ships(objdir):
    """helper.exe must be in the package: the updater runs it after every update.

    It is NSIS (uninstaller.nsi), built during `mach build` and shipped as
    uninstall/helper.exe. Nothing else in the build would notice if it stopped
    being built: the zip would still package fine and just quietly have no way
    to uninstall.
    """
    helper = objdir / "dist" / "bin" / "uninstall" / "helper.exe"
    if not helper.is_file():
        raise SystemExit(
            f"{helper} is missing: the browser would ship with no uninstaller.\n"
            "  It is built by browser/Makefile.in (libs:: -> installer/windows\n"
            "  uninstaller) via the $(CONFIG_DIR)/helper.exe rule in\n"
            "  toolkit/mozapps/installer/windows/nsis/makensis.mk. A makefile\n"
            "  that no longer parses that rule fails here instead of shipping.")
    print(f"[aether] uninstaller present: {helper.stat().st_size/1e6:.1f} MB")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", default=str(ROOT.parent / "firefox-src"))
    ap.add_argument("--artifact", action="store_true",
                    help="add --enable-artifact-builds for fast iteration")
    ap.add_argument("--package-only", action="store_true")
    args = ap.parse_args()

    src = Path(args.src)
    if not (src / "mach").exists():
        raise SystemExit(f"no Firefox checkout at {src}. Run scripts/sync.py first.")

    env = dict(os.environ)
    env["MOZCONFIG"] = str(ROOT / "mozconfig.windows")
    py = sys.executable

    if not args.package_only:
        # Windows note: ./mach normally runs inside start-shell.bat. Here we
        # invoke `mach build` through python so this also works on CI.
        run([py, "mach", "build"], cwd=str(src), env=env)

    run([py, "mach", "package"], cwd=str(src), env=env)

    version = firefox_version()
    objdir = src / "obj-aether"
    print(f"[aether] version {version}")
    assert_uninstaller_ships(objdir)

    # The shipped setup: stub UI + full installer packed offline. This must
    # run before the cleanup below, which deletes its inputs.
    run([py, str(ROOT / "scripts" / "make-stub-offline.py"),
         "--src", str(src), "--version", version], cwd=str(ROOT))

    dist = objdir / "dist"
    setup = dist / f"AetherSetup-{version}.exe"
    if not setup.is_file():
        raise SystemExit(f"make-stub-offline did not produce {setup.name}")
    print(f"[aether] setup: {setup} ({setup.stat().st_size/1e6:.1f} MB)")

    # Dist cleanup: the standalone installers either duplicate the setup
    # (full) or would download from Mozilla when run bare (stub), and the xpt
    # artifacts feed no later step. The zip stays: it is the portable build
    # for whoever compiles. Everything here is regenerated by `mach package`,
    # so nothing is lost. The txt metadata stays.
    for name in (f"aether-{version}.en-US.win64.installer.exe",
                 f"aether-{version}.en-US.win64.installer-stub.exe",
                 f"aether-{version}.en-US.win64.xpt_artifacts.zip"):
        p = dist / name
        if p.is_file():
            p.unlink()
            print(f"[aether] removed unused {name}")

    print("[aether] dist:")
    for f in sorted(dist.glob("*")):
        if f.is_file():
            print(f"  {f.name}  {f.stat().st_size/1e6:.1f} MB")
    print("[aether] build OK")


if __name__ == "__main__":
    main()
